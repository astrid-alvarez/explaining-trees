def get_path_nodes_for_class(target_class_name: str):
    target_idx = class_names.index(target_class_name)
    has_target_desc = np.zeros(n_nodes, dtype=bool)

    def dfs(u: int) -> bool:
        if is_leaf[u]:
            has_target_desc[u] = (pred_cls_idx[u] == target_idx)
            return has_target_desc[u]
        l = dfs(children_left[u]); r = dfs(children_right[u])
        has_target_desc[u] = l or r
        return has_target_desc[u]

    dfs(0)

    path_nodes = set()
    def mark(u: int):
        if not has_target_desc[u]:
            return
        path_nodes.add(u)
        if not is_leaf[u]:
            if has_target_desc[children_left[u]]:  mark(children_left[u])
            if has_target_desc[children_right[u]]: mark(children_right[u])
    mark(0)
    return path_nodes

