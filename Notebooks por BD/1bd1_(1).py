def evaluar_estabilidad(model, X, feature_names, noise_level=0.05, k=5, n_samples=50):
    # 1. Muestra aleatoria
    if len(X) > n_samples:
        indices_sample = np.random.choice(len(X), n_samples, replace=False)
        X_sample = X.iloc[indices_sample].copy()
    else:
        X_sample = X.copy()

    print(f"Evaluando estabilidad en muestra de {len(X_sample)} instancias...")

    # 2. SHAP Original
    explainer = shap.TreeExplainer(model)
    try:
        shap_orig_raw = explainer.shap_values(X_sample, check_additivity=False)
    except:
        shap_orig_raw = explainer.shap_values(X_sample)

    # Estandarizar a lista
    if not isinstance(shap_orig_raw, list):
        if len(np.array(shap_orig_raw).shape) == 3:
            shap_orig = [np.array(shap_orig_raw)[:, :, i] for i in range(np.array(shap_orig_raw).shape[2])]
        else:
            shap_orig = [np.array(shap_orig_raw)] # Caso binario simple
    else:
        shap_orig = shap_orig_raw

    # 3. Generar Ruido
    X_noisy = X_sample.copy()
    # Solo añadir ruido a columnas numéricas para evitar errores
    cols_numericas = X_noisy.select_dtypes(include=[np.number]).columns
    for col in cols_numericas:
        std = X_noisy[col].std()
        if std == 0: std = 0.01 # Evitar error en constantes
        noise = np.random.normal(0, std * noise_level, size=len(X_noisy))
        X_noisy[col] += noise

    # 4. SHAP Perturbado
    try:
        shap_pert_raw = explainer.shap_values(X_noisy, check_additivity=False)
    except:
        shap_pert_raw = explainer.shap_values(X_noisy)

    if not isinstance(shap_pert_raw, list):
        if len(np.array(shap_pert_raw).shape) == 3:
            shap_pert = [np.array(shap_pert_raw)[:, :, i] for i in range(np.array(shap_pert_raw).shape[2])]
        else:
            shap_pert = [np.array(shap_pert_raw)]
    else:
        shap_pert = shap_pert_raw

    # 5. Calcular Jaccard
    stability_scores = {}
    num_clases = len(shap_orig)

    for c in range(num_clases):
        jaccards = []
        for i in range(len(X_sample)):
            # Top K Original
            vals_orig = np.abs(shap_orig[c][i])
            top_idx_orig = set(np.argsort(vals_orig)[::-1][:k])

            # Top K Perturbado
            vals_pert = np.abs(shap_pert[c][i])
            top_idx_pert = set(np.argsort(vals_pert)[::-1][:k])

            inter = len(top_idx_orig.intersection(top_idx_pert))
            union = len(top_idx_orig.union(top_idx_pert))
            jaccard = inter / union if union > 0 else 0
            jaccards.append(jaccard)

        stability_scores[c] = np.mean(jaccards)

    return stability_scores

