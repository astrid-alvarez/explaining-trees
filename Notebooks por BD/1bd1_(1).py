def _arr_str_int(a):
    a = list(map(int, a))
    return "[" + ", ".join(str(x) for x in a) + "]"

def _arr_str_float(a):
    return "[" + ", ".join(f"{float(x):.2f}" for x in a) + "]"

def visualize_full_tree_graphviz_fixed_nice(
    model,
    feature_names,
    out_filename="ARBOL_GRAPHVIZ_NICE",
    dpi=220,
    ranksep="0.55",
    nodesep="0.35",
):
    tree_ = model.tree_

    dot = graphviz.Digraph(
        comment="Árbol de Decisión (legible, márgenes amplios)",
        engine="dot",
        format="png",
        graph_attr={
            "rankdir": "TB",
            "dpi": str(dpi),
            "ranksep": ranksep,
            "nodesep": nodesep,
            "pad": "0.2",
        },
        node_attr={
            "shape": "box",
            "style": "rounded,filled",
            "fontname": "Helvetica",
            "fontsize": "11",
            "margin": "0.16,0.10",
            "penwidth": "1.4",
        },
        edge_attr={
            "fontname": "Helvetica",
            "fontsize": "9",
        },
    )

    def add_node_and_edges(nid):
        counts_w = tree_.value[nid][0].astype(float)
        total_w  = counts_w.sum()
        probs    = counts_w / total_w if total_w > 0 else np.zeros_like(counts_w)

        samples  = int(tree_.n_node_samples[nid])
        est_cnts = np.rint(probs * samples).astype(int)

        maj_idx  = int(np.argmax(probs if total_w > 0 else counts_w))
        maj_name = class_names_ordered[maj_idx]
        color    = CLASS_COLORS.get(maj_name, "#EEEEEE")

        impurity = float(tree_.impurity[nid])
        is_leaf  = (tree_.children_left[nid] == tree_.children_right[nid])

        value_str = _arr_str_int(est_cnts)
        probs_str = _arr_str_float(probs)

        if is_leaf:
            label = (
                f"samples = {samples}\n"
                f"value = {value_str}\n"
                f"probs = {probs_str}\n"
                f"class = {maj_name}"
            )
            dot.node(str(nid), label=label, fillcolor=color, shape="ellipse")
        else:
            feat = feature_names[tree_.feature[nid]]
            thr  = float(tree_.threshold[nid])
            label = (
                f"{feat} <= {thr:.3f}\n"
                f"gini = {impurity:.3f} | samples = {samples}\n"
                f"value = {value_str}\n"
                f"probs = {probs_str}\n"
                f"class = {maj_name}"
            )
            dot.node(str(nid), label=label, fillcolor="#FFFFFF", shape="box")

            left  = tree_.children_left[nid]
            right = tree_.children_right[nid]
            dot.edge(str(nid), str(left),  label="True")
            dot.edge(str(nid), str(right), label="False")
            add_node_and_edges(left)
            add_node_and_edges(right)

    add_node_and_edges(0)
    path = dot.render(out_filename, cleanup=True)
    print(f"✓ PNG guardado: {path}")
    # CAMBIO AQUÍ: Usar IPImage en lugar de Image
    display(IPImage(filename=path))

