def fmt(x, k=2):
    return f"{x:.{k}f}"

def counts_str(v_float):
    """value como conteos enteros redondeados (evita truncado a 0)."""
    v_int = np.rint(np.asarray(v_float, dtype=float)).astype(int)
    return "[" + ", ".join(str(int(x)) for x in v_int) + "]"

# ========== 1) ÁRBOL EN TEXTO — MODELO GENERALIZADO ==========
def ascii_tree_global(prec=2, idioma="es"):
    """
    Árbol en texto (tipo export_text) para TODO el modelo.
    En las hojas se imprime:
      class: <pred> (samples=N, value=[...], soporte=XX.XX%, confianza=YY.YY%)
    Donde 'confianza' es hacia la clase predicha en esa hoja.
    """
    N_total = float(len(X))
    lines = []

    def dump(u, depth):
        indent = "|   " * depth
        if is_leaf[u]:
            v = values_raw[u].astype(float)
            total_leaf = v.sum()
            pred_idx = int(v.argmax())
            conf_pct = 100.0 * (v[pred_idx] / total_leaf) if total_leaf > 0 else 0.0
            supp_pct = 100.0 * (float(n_node_samples[u]) / N_total) if N_total > 0 else 0.0

            cname = class_names[pred_idx]
            n  = int(np.rint(n_node_samples[u]))
            val = counts_str(v)

            if idioma == "es":
                lines.append(
                    f"{indent}|--- class: {cname} (samples={n}, value={val}, "
                    f"soporte={fmt(supp_pct, prec)}%, confianza={fmt(conf_pct, prec)}%)"
                )
            else:
                lines.append(
                    f"{indent}|--- class: {cname} (samples={n}, value={val}, "
                    f"support={fmt(supp_pct, prec)}%, confidence={fmt(conf_pct, prec)}%)"
                )
            return

        feat = feature_names[features_idx[u]]
        thr  = thresholds[u]
        lines.append(f"{indent}|--- {feat} <= {fmt(thr, prec)}")
        dump(children_left[u], depth+1)
        lines.append(f"{indent}|--- {feat} > {fmt(thr, prec)}")
        dump(children_right[u], depth+1)

    dump(0, 0)
    return "\n".join(lines)

