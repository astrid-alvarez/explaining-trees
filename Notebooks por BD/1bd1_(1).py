def calcular_consistencia_jaccard(shap_vals_list, feature_list, class_list, k=5):
    """
    Compara las Top-K características más importantes según SHAP (Global)
    vs. las Top-K características más usadas en las Reglas del Árbol Especialista.
    """
    resultados = []

    # Asegurar que feature_list sea lista
    if hasattr(feature_list, 'tolist'):
        feature_list = feature_list.tolist()

    for i, class_name in enumerate(class_list):
        print(f"Analizando consistencia para clase: {class_name}...")

        # --- A) Top-K Features según SHAP (Promedio Absoluto Global) ---
        # shap_vals_list[i] es la matriz (Samples, Features)
        mean_abs_shap = np.mean(np.abs(shap_vals_list[i]), axis=0)

        # Obtener índices de los mayores valores
        top_indices_shap = np.argsort(mean_abs_shap)[::-1][:k]
        top_k_feats_shap = set([feature_list[idx] for idx in top_indices_shap])

        # --- B) Top-K Features según Reglas del Árbol (Extraído de los CSVs Parte 12) ---
        # Reconstruir nombre del archivo tal como se guardó en Parte 12
        safe_name = str(class_name).lower().replace(' ', '_').replace('>', 'gt').replace('<', 'lt')
        filename_csv = f"reglas_especializadas_clase_{safe_name}.csv"

        top_k_feats_tree = set()
        try:
            df_rules = pd.read_csv(filename_csv)

            # Estrategia: Tomar las features que aparecen en las reglas de mayor confianza
            # Tomamos las top 20 reglas para tener suficiente corpus
            top_rules = df_rules.head(20)

            # Conteo simple de frecuencia de features en las condiciones
            feat_counter = {}
            for cond_str in top_rules['conditions']:
                if pd.isna(cond_str): continue
                for feat in feature_list:
                    # Chequeo simple de substring (puede mejorarse con regex si los nombres son complejos)
                    if feat in cond_str:
                        feat_counter[feat] = feat_counter.get(feat, 0) + 1

            # Ordenar por frecuencia de aparición
            sorted_feats_tree = sorted(feat_counter, key=feat_counter.get, reverse=True)[:k]
            top_k_feats_tree = set(sorted_feats_tree)

        except FileNotFoundError:
            print(f"  ⚠ Advertencia: No se encontró {filename_csv}. Saltando comparación árbol.")

        # --- C) Cálculo de métricas ---
        intersection = top_k_feats_shap.intersection(top_k_feats_tree)
        union = top_k_feats_shap.union(top_k_feats_tree)

        jaccard = len(intersection) / len(union) if len(union) > 0 else 0.0

        resultados.append({
            "Clase": class_name,
            "Jaccard_Index": round(jaccard, 4),
            "Coincidencias": len(intersection),
            "Features_Comunes": list(intersection),
            "Solo_SHAP": list(top_k_feats_shap - top_k_feats_tree),
            "Solo_Arbol": list(top_k_feats_tree - top_k_feats_shap)
        })

    return pd.DataFrame(resultados)

