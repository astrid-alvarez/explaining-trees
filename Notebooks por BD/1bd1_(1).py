def seleccionar_prototipos_robusto(model, X, y_true, classes, map_dict):
    """
    Selecciona la instancia con mayor probabilidad predicha (y acierto correcto)
    para cada clase.
    """
    # 1. Obtener predicciones y probabilidades
    probs = model.predict_proba(X)
    preds = model.predict(X)

    # 2. Normalizar y_true a array numpy para indexación booleana
    if isinstance(y_true, pd.Series):
        y_true_arr = y_true.values
    else:
        y_true_arr = np.array(y_true)

    prototipos = {}

    print(f"Buscando prototipos en {len(X)} instancias de prueba...")

    for class_name in classes:
        # Obtener el índice numérico de la clase usando el mapa (ej: 'Dropout' -> 0)
        if class_name in map_dict:
            idx_class_num = map_dict[class_name]
        else:
            # Fallback si el mapa no coincide exactamente
            print(f"Advertencia: '{class_name}' no encontrado en target_map. Usando índice de lista.")
            idx_class_num = classes.index(class_name)

        # 3. Filtrar: Instancias que SON de esa clase Y fueron PREDICHAS como esa clase
        mask = (y_true_arr == idx_class_num) & (preds == idx_class_num)

        count_matches = np.sum(mask)

        if count_matches > 0:
            # Índices relativos dentro de X_test
            indices_relativos = np.where(mask)[0]

            # Extraer probabilidades solo para esta clase
            probs_de_clase = probs[indices_relativos, idx_class_num]

            # Encontrar el índice del máximo valor
            best_sub_idx = np.argmax(probs_de_clase)

            # Índice real en el array X_test
            idx_final = indices_relativos[best_sub_idx]
            max_prob = probs_de_clase[best_sub_idx]

            prototipos[class_name] = {
                'index_loc': idx_final,       # Índice posicional (0 a N-1) para usar con iloc/numpy
                'prob': max_prob,
                'true_label': class_name,
                'class_idx_int': idx_class_num
            }
            print(f"  ✓ Prototipo {class_name:10s}: Instancia #{idx_final:<4} | Confianza: {max_prob*100:.2f}%")
        else:
            print(f"  ⚠ No se encontraron aciertos correctos para {class_name}")
            prototipos[class_name] = None

    return prototipos

