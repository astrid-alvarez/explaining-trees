def build_compacted_graphviz_strict(modelo, clase, tau, soporte, keep, dpi=220):
    """
    Árbol COMPACTADO ESPECIALISTA para una clase:

    1) Usa máscara estricta _keep_mask_strict_monotonic → solo caminos con p_hijo ≥ p_padre.
    2) En cada camino, compacta desigualdades por feature en UNA condición.
    3) Construye árbol virtual donde cada nodo interno tiene:
           - condición compacta,
           - métricas del nodo real (PRIMERA aparición de la feature).
    4) En el árbol virtual volvemos a aplicar poda local:
           solo dibujamos aristas donde p_hijo >= p_padre.
       (por si la compartición de nodos entre caminos generara violaciones).

    Se omiten nodos/reglas que rompeln la reglas.
    """
    import graphviz
    from IPython.display import Image as IPImage, display

    tree_ = modelo.tree_
    cidx = class_names.index(clase)
    color_clase = CLASS_COLORS.get(clase, "#FFFFFF")

    # --- 1) caminos raíz→hoja válidos, ya filtrados por monotonía estricta ---
    paths = _get_paths_for_class(tree_, keep)    # leaf -> [(feat,thr,op,node), ...]

    if not paths:
        print(f"  → No hay caminos compactables para la clase {clase}.")
        return None

    # --- 2) compactar condiciones por camino ---
    compacted_paths = {}                         # leaf -> [ {text, node_idx}, ... ]
    for leaf, path in paths.items():
        compacted_paths[leaf] = _compact_path_to_intervals(path)

    # --- 3) construir árbol virtual: nodos internos y hojas ---
    next_id = 0
    node_children = {}   # node_id -> dict(cond_text -> child_node_id)
    node_label    = {}   # node_id -> texto de condición (para internos)
    node_src_idx  = {}   # node_id -> índice de nodo real representativo
    leaf_by_node  = {}   # node_id -> leaf_idx real asociado

    def new_internal(label_text, src_idx=None):
        nonlocal next_id
        node_id = f"N{next_id}"
        next_id += 1
        node_children[node_id] = {}
        node_label[node_id] = label_text
        node_src_idx[node_id] = src_idx
        return node_id

    # raíz virtual
    root_id = new_internal("ROOT", src_idx=None)

    # Construir la estructura compartida de prefijos compactados
    for leaf_idx, cond_list in compacted_paths.items():
        current = root_id
        for cond_info in cond_list:
            text    = cond_info["text"]
            src_idx = cond_info["node_idx"]

            children = node_children[current]
            if text not in children:
                child_id = new_internal(text, src_idx=src_idx)
                children[text] = child_id
            current = children[text]
        # el nodo interno final corresponde a una hoja real
        leaf_by_node[current] = leaf_idx

    # --- 4) función auxiliar para obtener p(clase) de un nodo real ---
    def prob_of_src(src_idx: int) -> float:
        if src_idx is None or src_idx < 0:
            return 0.0
        return _node_prob_for_class(tree_, src_idx, cidx)

    # --- 5) dibujar con poda estricta en el árbol virtual ---
    dot = graphviz.Digraph(
        graph_attr={
            "rankdir": "TB",
            "dpi": str(dpi),
            "splines": "true",
            "nodesep": "0.35",
            "ranksep": "0.5",
            "fontname": "Helvetica",
            "label": f"Clase: {clase} | τ={tau:.2f} | soporte≥{soporte} | ÁRBOL COMPACTADO (MONOTÓNICO ESTRICTO)",
            "labelloc": "t",
        },
        node_attr={
            "shape": "box",
            "style": "rounded,filled",
            "fontname": "Helvetica",
            "fontsize": "11",
            "penwidth": "1.6",
            "color": "black",
        },
        edge_attr={
            "fontname": "Helvetica",
            "fontsize": "10",
            "color": "black",
            "arrowsize": "0.8",
        },
    )

    # cache de prob de cada nodo virtual
    prob_virtual = {}

    def draw(node_id, parent_p: float = 0.0):
        # Probabilidad en este nodo virtual
        src_idx = node_src_idx.get(node_id, None)
        p_here  = prob_of_src(src_idx) if src_idx is not None else parent_p
        prob_virtual[node_id] = p_here

        # Nodo interno
        if node_id == root_id:
            label = "ROOT"
            dot.node(node_id, label=label, fillcolor=color_clase)
        else:
            base_cond = node_label[node_id]
            if src_idx is not None and src_idx >= 0:
                w, probs, samples = _node_counts_and_probvec(tree_, src_idx)
                gini = float(tree_.impurity[src_idx])
                p_c  = float(probs[cidx]) if probs.size > 0 else 0.0
                est_counts = np.rint(probs * samples).astype(int)
                pred_lbl = class_names[int(np.argmax(w))]
                label = (
                    f"{base_cond}\n"
                    f"gini = {gini:.3f} | samples = {samples}\n"
                    f"p({clase}) = {p_c:.4f}\n"
                    f"class = {pred_lbl}"
                )
            else:
                label = base_cond

            dot.node(node_id, label=label, fillcolor=color_clase)

        # Hijos internos (con poda p_hijo < p_padre)
        for cond_text, child_id in node_children[node_id].items():
            src_child = node_src_idx.get(child_id, None)
            p_child   = prob_of_src(src_child) if src_child is not None else p_here

            if p_child < p_here:
                # Poda virtual: no dibujamos ramas que rompen monotonía
                continue

            dot.edge(node_id, child_id, label="")
            draw(child_id, p_here)

        # Hoja asociada (si existe)
        if node_id in leaf_by_node:
            leaf_idx = leaf_by_node[node_id]
            w_leaf, probs_leaf, samples_leaf = _node_counts_and_probvec(tree_, leaf_idx)
            p_c_leaf = float(probs_leaf[cidx]) if probs_leaf.size > 0 else 0.0
            est_counts_leaf = np.rint(probs_leaf * samples_leaf).astype(int)
            pred_lbl_leaf = class_names[int(np.argmax(w_leaf))]

            # por construcción de la máscara estricta, p_leaf >= p_here
            leaf_label = (
                f"samples = {samples_leaf}\n"
                f"value = {_arr_str_int(est_counts_leaf)}\n"
                f"p({clase}) = {p_c_leaf:.4f}\n"
                f"class = {pred_lbl_leaf}"
            )
            leaf_node_id = f"L{leaf_idx}"
            dot.node(leaf_node_id, label=leaf_label,
                     shape="ellipse", fillcolor=color_clase)
            dot.edge(node_id, leaf_node_id, label="")

    draw(root_id, parent_p=0.0)

    # --- guardar PNG ---
    safe_clase = clase.replace('>', 'MAS').replace('<', 'MENOS').replace(' ', '_')
    fname = f"ARBOL_COMPACTADO_MONO_{safe_clase}"
    path = dot.render(fname, format="png", cleanup=True)
    print(f"✓ Árbol compactado MONÓTONO para {clase} guardado como: {path}")
    display(IPImage(filename=path))
    return path

