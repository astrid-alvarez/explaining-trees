def draw_paths_per_class_graphviz(
    model,
    feature_names,
    class_names,
    out_prefix="ARBOL_POR_CLASE_AJUSTADO_",
    dpi=220,
    node_font="Helvetica",
    edge_font="Helvetica",
):
    tree = model.tree_

    def counts_probs_for_node(u: int):
        """Devuelve (counts_int, probs) usando pesos -> probabilidades -> conteos aprox."""
        w = value_raw[u].astype(float)                 # pesos por clase
        w_sum = w.sum()
        if w_sum > 0:
            probs = w / w_sum
        else:
            probs = np.zeros_like(w, dtype=float)
        samples = int(tree.n_node_samples[u])
        counts = np.rint(probs * samples).astype(int)  # reconstrucción de conteos
        return counts, probs

    def fmt_counts(counts):
        return "[" + ", ".join(str(int(x)) for x in counts) + "]"

    def fmt_probs(probs):
        return "[" + ", ".join(f"{p:.2f}" for p in probs) + "]"

    for cls_name in class_names:
        color = CLASS_COLORS[cls_name]
        path_nodes = get_path_nodes_for_class(cls_name)
        if not path_nodes:
            print(f"(i) No hay camino para la clase: {cls_name}")
            continue

        dot = graphviz.Digraph(
            comment=f"Caminos hacia {cls_name}",
            graph_attr={
                "dpi": str(dpi),
                "rankdir": "TB",
                "splines": "true",
                "nodesep": "0.35",
                "ranksep": "0.45",
                "fontname": node_font,
            },
            node_attr={
                "shape": "box",
                "style": "filled,rounded",
                "fontname": node_font,
                "fontsize": "14",
                "penwidth": "2",
                "color": "black",
            },
            edge_attr={
                "fontname": edge_font,
                "fontsize": "12",
                "color": "black",
                "arrowsize": "0.8",
            },
        )

        def add_nodes_and_edges(u: int):
            if u not in path_nodes:
                return

            counts, probs = counts_probs_for_node(u)
            samples = int(tree.n_node_samples[u])
            gini    = float(tree.impurity[u])
            majority_cls = class_names[int(pred_cls_idx[u])]

            if is_leaf[u]:
                label = (
                    f"samples = {samples}\n"
                    f"value = {fmt_counts(counts)}\n"
                    f"probs = {fmt_probs(probs)}\n"
                    f"class = {majority_cls}"
                )
                dot.node(str(u), label=label, fillcolor=color, shape="ellipse")
            else:
                feat = feature_names[int(tree.feature[u])]
                thr  = float(tree.threshold[u])
                label = (
                    f"{feat} <= {thr:.3f}\n"
                    f"gini = {gini:.3f} | samples = {samples}\n"
                    f"value = {fmt_counts(counts)}\n"
                    f"probs = {fmt_probs(probs)}\n"
                    f"class = {majority_cls}"
                )
                dot.node(str(u), label=label, fillcolor=color, shape="box")

                lc = int(children_left[u]);  rc = int(children_right[u])
                if lc in path_nodes:
                    dot.edge(str(u), str(lc), label="True")
                    add_nodes_and_edges(lc)
                if rc in path_nodes:
                    dot.edge(str(u), str(rc), label="False")
                    add_nodes_and_edges(rc)

        add_nodes_and_edges(0)

        out_name = f"{out_prefix}{_safe_name(cls_name)}"
        dot.render(out_name, format="png", cleanup=True)
        print(f"✓ Guardado: {out_name}.png")
        # CORRECCIÓN CRÍTICA: Usar IPImage en lugar de Image
        display(IPImage(filename=f"{out_name}.png"))

