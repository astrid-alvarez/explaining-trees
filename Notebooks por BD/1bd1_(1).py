# MÁSCARA MONOTÓNICA ESTRICTA (PODA), BASADA EN PARTE 14
# ================================================================================================
def _keep_mask_strict_monotonic(tree_, class_idx, tau, min_samples_to_keep: int = 0):
    """
    Mantiene SOLO caminos donde la probabilidad de la clase es NO DECRECIENTE:
        p_hijo >= p_padre en cada paso.

    Además, la hoja:
        - predice la clase objetivo,
        - tiene p >= tau,
        - tiene soporte >= min_samples_to_keep.

    Cualquier rama que viole p_hijo < p_padre se poda completamente.
    """
    n = tree_.node_count
    keep = np.zeros(n, dtype=bool)

    def dfs(u: int, parent_p: float = 0.0) -> bool:
        samples_u = int(tree_.n_node_samples[u])
        p_current = _node_prob_for_class(tree_, u, class_idx)

        # Poda inmediata si viola monotonía local
        if p_current < parent_p:
            return False

        if _is_leaf(tree_, u):
            ok = (
                _predicted_class_idx(tree_, u) == class_idx and
                p_current >= tau and
                samples_u >= min_samples_to_keep
            )
            if ok:
                keep[u] = True
            return ok

        L, R = int(tree_.children_left[u]), int(tree_.children_right[u])
        left_ok  = dfs(L, p_current)
        right_ok = dfs(R, p_current)

        if left_ok or right_ok:
            keep[u] = True
            return True

        # Este nodo no conduce a hojas válidas
        return False

    dfs(0, 0.0)
    return keep

# ================================================================================================
# CAMINOS RAÍZ→HOJA Y COMPACTACIÓN DE DESIGUALDADES
# ================================================================================================
def _get_paths_for_class(tree_, keep):
    """
    Devuelve dict: leaf_id -> lista de (feat_idx, thr, op, node_id)
    op = '<=' si vamos por la izquierda (True), '>' si vamos por la derecha (False).
    Solo recorre nodos con keep=True.
    """
    paths = {}

    def dfs(u, path):
        if not keep[u]:
            return

        if _is_leaf(tree_, u):
            paths[u] = list(path)
            return

        feat_idx = int(tree_.feature[u])
        thr = float(tree_.threshold[u])
        L = int(tree_.children_left[u])
        R = int(tree_.children_right[u])

        # Izquierda: condición feat <= thr
        if keep[L]:
            dfs(L, path + [(feat_idx, thr, "<=", u)])
        # Derecha: condición feat > thr
        if keep[R]:
            dfs(R, path + [(feat_idx, thr, ">", u)])

    dfs(0, [])
    return paths

def _compact_path_to_intervals(path):
    """
    path: lista de (feat_idx, thr, op, node_id) en orden de recorrido real.
    Compacta, por feature, la intersección de todas sus desigualdades en el camino.

    IMPORTANTE PARA MONOTONÍA:
      - El nodo "representativo" de cada feature será el de PRIMERA aparición
        (mismas estadísticas que el árbol original en ese punto).
      - El orden de las condiciones en el árbol compacto respeta ese orden
        de primera aparición (subsecuencia de un camino real, que ya es monótono).

    Devuelve lista de dicts:
        {"text": "<condición compacta>",
         "node_idx": índice de nodo representativo}
    """
    import math

    bounds = {}   # feat_name -> {lower, upper, node_idx, first_pos}
    pos = 0

    for feat_idx, thr, op, node_id in path:
        if feat_idx < 0:
            pos += 1
            continue

        feat_name = feature_names[feat_idx]

        if feat_name not in bounds:
            # Primera vez que vemos esta feature → fijamos nodo representativo aquí
            bounds[feat_name] = {
                "lower": -math.inf,
                "upper":  math.inf,
                "node_idx": node_id,     # <-- nodo de PRIMERA aparición
                "first_pos": pos
            }

        b = bounds[feat_name]

        # Actualizar intervalo (intersección de desigualdades)
        if op == "<=":
            b["upper"] = min(b["upper"], thr)
        else:  # '>'
            b["lower"] = max(b["lower"], thr)

        pos += 1

    # Construir lista en el orden de primera aparición en el camino
    conds = []
    for feat_name in sorted(bounds.keys(), key=lambda f: bounds[f]["first_pos"]):
        b = bounds[feat_name]
        lo, hi, node_idx = b["lower"], b["upper"], b["node_idx"]

        if lo == -math.inf and hi == math.inf:
            continue
        elif lo == -math.inf:
            text = f"{feat_name} <= {hi:.3f}"
        elif hi == math.inf:
            text = f"{feat_name} > {lo:.3f}"
        else:
            text = f"{lo:.3f} < {feat_name} <= {hi:.3f}"

        conds.append({"text": text, "node_idx": node_idx})

    return conds

