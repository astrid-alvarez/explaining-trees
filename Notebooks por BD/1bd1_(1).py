def _arr_str_int(a):
    a = list(map(int, a))
    return "[" + ", ".join(str(x) for x in a) + "]"

def _is_leaf(tree_, u: int) -> bool:
    return tree_.children_left[u] == -1

def _predicted_class_idx(tree_, u: int) -> int:
    """
    Índice de la clase predicha en el nodo u.
    Funciona tanto si value tiene forma (n_nodes, n_classes)
    como (n_nodes, 1, n_classes).
    """
    v = np.asarray(tree_.value[u], dtype=float)
    v = v.reshape(-1)        # vector 1D de tamaño n_clases
    return int(np.argmax(v))


def _node_prob_for_class(tree_, u: int, class_idx: int) -> float:
    """
    Probabilidad de la clase 'class_idx' en el nodo u.
    Compatibles con tree_.value de cualquier forma estándar.
    """
    v = np.asarray(tree_.value[u], dtype=float)
    v = v.reshape(-1)        # [n_clases]
    s = v.sum()
    if s <= 0:
        return 0.0
    return float(v[class_idx] / s)


def _node_counts_and_probvec(tree_, u: int):
    """
    Devuelve:
       - w: vector 1D con los conteos por clase
       - probs: vector 1D con las probabilidades por clase
       - samples: número total de muestras en el nodo
    """
    v = np.asarray(tree_.value[u], dtype=float)
    w = v.reshape(-1)        # [n_clases]
    s = w.sum()
    if s > 0:
        probs = w / s
    else:
        probs = np.zeros_like(w)
    samples = int(tree_.n_node_samples[u])
    return w, probs, samples


def _max_leaf_prob_for_class_with_support(tree_, class_idx: int, min_samples: int) -> float:
    maxp = 0.0
    for u in range(tree_.node_count):
        if _is_leaf(tree_, u) and _predicted_class_idx(tree_, u) == class_idx:
            if int(tree_.n_node_samples[u]) >= int(min_samples):
                p = _node_prob_for_class(tree_, u, class_idx)
                if p > maxp:
                    maxp = p
    return maxp

