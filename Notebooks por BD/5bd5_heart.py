def evaluar_fidelidad_surrogate(model_complex, X, y_pred_complex, classes):
    fidelity_scores = {}

    for i, class_val in enumerate(classes):
        # Target binario: ¿El modelo complejo predijo esta clase? (1 o 0)
        # Si classes son strings, asumimos que y_pred son ints (indices)
        if isinstance(class_val, str):
             target_binary = (y_pred_complex == i).astype(int)
        else:
             target_binary = (y_pred_complex == class_val).astype(int)

        # Si solo hay una clase (ej. nunca predijo '4'), fidelidad es trivial 1.0
        if len(np.unique(target_binary)) < 2:
            fidelity_scores[i] = 1.0
            continue

        # Entrenar Árbol Sustituto (Explicable, profundidad 3)
        surrogate = DecisionTreeClassifier(max_depth=3, random_state=42)
        surrogate.fit(X, target_binary)

        # Comparar predicciones
        surrogate_preds = surrogate.predict(X)
        fidelity = accuracy_score(target_binary, surrogate_preds)
        fidelity_scores[i] = fidelity

    return fidelity_scores

