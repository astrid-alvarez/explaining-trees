# CAMINOS RAÍZ→HOJA Y COMPACTACIÓN DE DESIGUALDADES
# ================================================================================================
def _get_paths_for_class(tree_, keep):
    """
    Devuelve dict: leaf_id -> lista de (feat_idx, thr, op, node_id)
    op = '<=' si vamos por la izquierda, '>' si vamos por la derecha.
    Solo recorre nodos con keep=True.
    """
    paths = {}

    def dfs(u, path):
        if not keep[u]:
            return

        if _is_leaf(tree_, u):
            paths[u] = list(path)
            return

        feat_idx = int(tree_.feature[u])
        thr = float(tree_.threshold[u])
        L = int(tree_.children_left[u])
        R = int(tree_.children_right[u])

        if keep[L]:
            dfs(L, path + [(feat_idx, thr, "<=", u)])
        if keep[R]:
            dfs(R, path + [(feat_idx, thr, ">", u)])

    dfs(0, [])
    return paths

def _compact_path_to_intervals(path):
    """
    Compacta, por feature, la intersección de desigualdades a lo largo del camino.
    Devuelve lista de dicts:
        {"text": "<condición compacta>", "node_idx": índice de nodo representativo}
    """
    bounds = {}   # feat_name -> {lower, upper, node_idx, first_pos}
    pos = 0

    for feat_idx, thr, op, node_id in path:
        if feat_idx < 0:
            pos += 1
            continue

        feat_name = feature_names[feat_idx]

        if feat_name not in bounds:
            bounds[feat_name] = {
                "lower": -math.inf,
                "upper":  math.inf,
                "node_idx": node_id,
                "first_pos": pos
            }

        b = bounds[feat_name]

        if op == "<=":
            b["upper"] = min(b["upper"], thr)
        else:
            b["lower"] = max(b["lower"], thr)

        pos += 1

    conds = []
    for feat_name in sorted(bounds.keys(), key=lambda f: bounds[f]["first_pos"]):
        b = bounds[feat_name]
        lo, hi, node_idx = b["lower"], b["upper"], b["node_idx"]

        if lo == -math.inf and hi == math.inf:
            continue
        elif lo == -math.inf:
            text = f"{feat_name} <= {hi:.3f}"
        elif hi == math.inf:
            text = f"{feat_name} > {lo:.3f}"
        else:
            text = f"{lo:.3f} < {feat_name} <= {hi:.3f}"

        conds.append({"text": text, "node_idx": node_idx})

    return conds

