def _keep_mask_strict_monotonic(tree_, class_pos, tau, min_samples_to_keep: int = 0):
    """
    Mantiene SOLO caminos donde la probabilidad de la clase (class_pos) es NO DECRECIENTE:
        p_hijo >= p_padre en cada paso.

    Además, la hoja:
        - predice la clase objetivo (por posición),
        - tiene p >= tau,
        - tiene soporte >= min_samples_to_keep.
    """
    n = tree_.node_count
    keep = np.zeros(n, dtype=bool)

    def dfs(u: int, parent_p: float = 0.0) -> bool:
        samples_u = int(tree_.n_node_samples[u])
        p_current = _node_prob_for_class(tree_, u, class_pos)

        # Poda inmediata si viola monotonía local
        if p_current < parent_p:
            return False

        if _is_leaf(tree_, u):
            ok = (
                _predicted_class_pos(tree_, u) == class_pos and
                p_current >= tau and
                samples_u >= min_samples_to_keep
            )
            if ok:
                keep[u] = True
            return ok

        L, R = int(tree_.children_left[u]), int(tree_.children_right[u])
        left_ok  = dfs(L, p_current)
        right_ok = dfs(R, p_current)

        if left_ok or right_ok:
            keep[u] = True
            return True

        return False

    dfs(0, 0.0)
    return keep

