    N_total = float(len(X_scaled))
    lines = []

    def dump(u, depth):
        indent = "|   " * depth
        if is_leaf[u]:
            v = values_raw[u].astype(float)
            total_leaf = v.sum()
            pred_idx = int(v.argmax())

            # ID de clase tal como lo ve el modelo
