def ascii_tree_por_clase(class_id_objetivo, prec=2, idioma="es"):
    """
    Genera el árbol en texto para la CLASE OBJETIVO indicada por su ID interno.
    Ej: class_id_objetivo = 2 → 'Enfermedad moderada' en HEART.

    Solo se muestran ramas que conducen a hojas cuya clase mayoritaria es esa clase.
    """
    # Posición de esta clase ID en el vector de probabilidades
    try:
        target_pos = model_class_ids.index(class_id_objetivo)
    except ValueError:
        raise ValueError(f"El class_id={class_id_objetivo} no está en modelo_generalizado.classes_")

    class_label_objetivo = class_id_to_label[class_id_objetivo]

    # Usar X_scaled para soporte relativo
    N_total = float(len(X_scaled))

    # 1) Marcar nodos que contienen hojas de la clase objetivo (en términos de POSICIÓN)
    has_target = np.zeros(n_nodes, dtype=bool)

    def marcar(u):
        if is_leaf[u]:
            # v.argmax() → posición de clase mayoritaria en values_raw[u]
            has_target[u] = (values_raw[u].argmax() == target_pos)
            return has_target[u]
        lt = marcar(children_left[u])
        rt = marcar(children_right[u])
        has_target[u] = lt or rt
        return has_target[u]

    marcar(0)

    # 2) Recorrer árbol y construir texto solo con ramas relevantes
    lines = []

    def volcar(u, depth):
        indent = "|   " * depth
        if is_leaf[u]:
            v = values_raw[u].astype(float)
            total_leaf = v.sum()
            samples_leaf = float(n_node_samples[u])

            # Confianza respecto a la clase OBJETIVO
            conf_pct = 100.0 * (v[target_pos] / total_leaf) if total_leaf > 0 else 0.0
            supp_pct = 100.0 * (samples_leaf / N_total) if N_total > 0 else 0.0

            # Clase mayoritaria en esa hoja (posición → ID → etiqueta)
            maj_pos = int(v.argmax())
            maj_id  = model_class_ids[maj_pos]
            maj_label = class_id_to_label[maj_id]

            n = int(np.rint(n_node_samples[u]))
            value_str = pretty_value_counts(v)

            if idioma == "es":
                line = (
                    f"{indent}|--- class: {maj_label} "
                    f"(samples={n}, value={value_str}, soporte={fmt(supp_pct, prec)}%, "
                    f"confianza={fmt(conf_pct, prec)}%)"
                )
            else:
                line = (
                    f"{indent}|--- class: {maj_label} "
                    f"(samples={n}, value={value_str}, support={fmt(supp_pct, prec)}%, "
                    f"confidence={fmt(conf_pct, prec)}%)"
                )
            lines.append(line)
            return

        # Nodo interno
        feat_idx = features_idx[u]
        if feat_idx < 0 or feat_idx >= len(feature_names):
            feat_name = f"Feature_{feat_idx}"
        else:
            feat_name = feature_names[feat_idx]

        thr = thresholds[u]

        if has_target[children_left[u]]:
            lines.append(f"{indent}|--- {feat_name} <= {fmt(thr, prec)}")
            volcar(children_left[u], depth + 1)
        if has_target[children_right[u]]:
            lines.append(f"{indent}|--- {feat_name} > {fmt(thr, prec)}")
            volcar(children_right[u], depth + 1)

    volcar(0, 0)
    return class_label_objetivo, "\n".join(lines)

