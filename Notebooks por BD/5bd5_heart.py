def calcular_rank_correlation(modelo, shap_vals_list, classes, mapa=None):
    resultados = []

    # 1. Obtener Importancia Global del Árbol (Criterio Gini/Entropía)
    # Esta es la "opinión" estructural del modelo sobre qué variables importan
    importancia_arbol = modelo.feature_importances_

    for i, class_id in enumerate(classes):
        nombre_real = str(class_id)
        if mapa: nombre_real = mapa.get(class_id, str(class_id))

        # 2. Obtener Importancia SHAP para esta clase
        if isinstance(shap_vals_list, list):
            shap_class = shap_vals_list[i]
        else:
            shap_class = shap_vals_list

        # Promedio absoluto de los valores SHAP (Magnitud de impacto)
        importancia_shap = np.mean(np.abs(shap_class), axis=0)

        # 3. Calcular Correlación de Spearman
        # Compara los rangos (1ro, 2do, 3ro...) no los valores crudos
        corr, p_value = spearmanr(importancia_shap, importancia_arbol)

        resultados.append({
            "Clase": nombre_real,
            "Rank_Correlation": round(corr, 4),
            "Significancia_P": round(p_value, 4)
        })

    return pd.DataFrame(resultados)

