def _arr_str_int(a):
    a = list(map(int, a))
    return "[" + ", ".join(str(x) for x in a) + "]"

def _is_leaf(tree_, u: int) -> bool:
    return tree_.children_left[u] == -1

def _predicted_class_pos(tree_, u: int) -> int:
    """
    Índice POSICIONAL de la clase predicha en el nodo u.
    (0..n_clases-1, coincide con posición en model_class_ids)
    """
    v = np.asarray(tree_.value[u], dtype=float)
    v = v.reshape(-1)
    return int(np.argmax(v))

def _node_prob_for_class(tree_, u: int, class_pos: int) -> float:
    """
    Probabilidad de la clase de índice posicional 'class_pos' en el nodo u.
    """
    v = np.asarray(tree_.value[u], dtype=float).reshape(-1)
    s = v.sum()
    if s <= 0:
        return 0.0
    return float(v[class_pos] / s)

def _node_counts_and_probvec(tree_, u: int):
    """
    Devuelve:
       - w: vector 1D con conteos por clase (pesos)
       - probs: vector 1D con las probabilidades por clase
       - samples: número total de muestras en el nodo
    """
    v = np.asarray(tree_.value[u], dtype=float)
    w = v.reshape(-1)
    s = w.sum()
    if s > 0:
        probs = w / s
    else:
        probs = np.zeros_like(w)
    samples = int(tree_.n_node_samples[u])
    return w, probs, samples

def _max_leaf_prob_for_class_with_support(tree_, class_pos: int, min_samples: int) -> float:
    """
    τ_max alcanzable para una clase (por posición) con soporte mínimo dado.
    """
    maxp = 0.0
    for u in range(tree_.node_count):
        if _is_leaf(tree_, u) and _predicted_class_pos(tree_, u) == class_pos:
            if int(tree_.n_node_samples[u]) >= int(min_samples):
                p = _node_prob_for_class(tree_, u, class_pos)
                if p > maxp:
                    maxp = p
    return maxp

