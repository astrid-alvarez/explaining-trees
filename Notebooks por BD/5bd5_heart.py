def calcular_coverage(modelo, X_data, y_data, classes, mapa=None):
    resultados = []

    # Obtener en qué hoja cae cada instancia
    leaf_ids = modelo.apply(X_data)
    tree_ = modelo.tree_

    # Asegurar formato numpy para y_data
    y_arr = y_data.values if isinstance(y_data, pd.Series) else y_data

    for i, class_id in enumerate(classes):
        nombre_real = str(class_id)
        if mapa: nombre_real = mapa.get(class_id, str(class_id))

        # 1. Filtrar las instancias que REALMENTE son de esta clase
        if isinstance(class_id, str):
             indices_clase = np.where(y_arr == i)[0]
        else:
             indices_clase = np.where(y_arr == class_id)[0]

        total_instancias = len(indices_clase)

        if total_instancias == 0:
            resultados.append({"Clase": nombre_real, "Cobertura_%": 0.0})
            continue

        # 2. Verificar si cayeron en una hoja que predice su misma clase
        hits = 0
        hojas_instancias = leaf_ids[indices_clase]

        for node_id in hojas_instancias:
            # ¿Qué clase predice esta hoja?
            pred_class_hoja = np.argmax(tree_.value[node_id])

            # Si la hoja predice lo mismo que la clase real, es una cobertura exitosa
            # (La regla especialista funcionó para esta instancia)
            if pred_class_hoja == i:
                hits += 1

        coverage_pct = (hits / total_instancias) * 100

        resultados.append({
            "Clase": nombre_real,
            "Total_Instancias": total_instancias,
            "Instancias_Cubiertas": hits,
            "Cobertura_%": round(coverage_pct, 2)
        })

    return pd.DataFrame(resultados)

