def calcular_reduccion_complejidad_max(modelo_global, classes, mapa=None):
    """
    Comparar la Profundidad Máxima del árbol global (Complejidad Total)
    con la Profundidad Promedio de las reglas por clase.
    """
    resultados = []
    tree_ = modelo_global.tree_

    # 1. Obtener la Profundidad Máxima del Modelo Global (El "Techo" de complejidad)
    profundidad_max_global = modelo_global.get_depth()
    print(f"Profundidad Máxima del Árbol Global: {profundidad_max_global}")

    # 2. Iterar por cada clase
    for i, class_id in enumerate(classes):
        # Definir nombre
        nombre_real = str(class_id)
        if mapa: nombre_real = mapa.get(class_id, str(class_id))

        longitudes = []

        # Recorrer el árbol para encontrar reglas de esta clase
        stack = [(0, 0)]
        while len(stack) > 0:
            node_id, depth = stack.pop()

            if tree_.children_left[node_id] == -1: # Es hoja
                pred_class = np.argmax(tree_.value[node_id])

                # Ajuste de índice
                target_idx = i

                if pred_class == target_idx:
                    longitudes.append(depth)
            else:
                stack.append((tree_.children_left[node_id], depth + 1))
                stack.append((tree_.children_right[node_id], depth + 1))

        # Calcular promedio del especialista
        profundidad_especialista = np.mean(longitudes) if longitudes else 0
        num_reglas = len(longitudes)

        # 3. Calcular Reducción (%) respecto al MÁXIMO global
        if profundidad_max_global > 0:
            reduccion = (1 - (profundidad_especialista / profundidad_max_global)) * 100
        else:
            reduccion = 0

        resultados.append({
            "Clase": nombre_real,
            "Complejidad_Global_(Max_Depth)": profundidad_max_global,
            "Complejidad_Especialista_(Avg)": round(profundidad_especialista, 2),
            "Reduccion_Cognitiva_%": round(reduccion, 2),
            "Reglas_Extraidas": num_reglas
        })

    return pd.DataFrame(resultados)

