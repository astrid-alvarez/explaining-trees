def draw_paths_per_class_graphviz(
    model,
    feature_names,
    class_ids,
    out_prefix="ARBOL_POR_CLASE_",
    dpi=220,
    node_font="Helvetica",
    edge_font="Helvetica",
):
    tree = model.tree_
    n_nodes = tree.node_count
    children_left  = tree.children_left
    children_right = tree.children_right
    is_leaf = (children_left == -1)

    # value_raw y predicciones ya definidas arriba, pero recalculamos por seguridad
    if tree.value.ndim == 3:
        value_raw_local = tree.value.squeeze(1)
    else:
        value_raw_local = tree.value
    pred_cls_idx_local = value_raw_local.argmax(axis=1)

    def counts_probs_for_node(u: int):
        w = value_raw_local[u].astype(float)
        w_sum = w.sum()
        if w_sum > 0:
            probs = w / w_sum
        else:
            probs = np.zeros_like(w, dtype=float)
        samples = int(tree.n_node_samples[u])
        counts = np.rint(probs * samples).astype(int)
        return counts, probs

    def fmt_counts(counts):
        return "[" + ", ".join(str(int(x)) for x in counts) + "]"

    def fmt_probs(probs):
        return "[" + ", ".join(f"{p:.2f}" for p in probs) + "]"

    for class_id in class_ids:
        # Posición de esta clase en el vector de probabilidades
        try:
            target_pos = model_class_ids.index(class_id)
        except ValueError:
            print(f"(i) La clase ID={class_id} no está en modelo_generalizado.classes_. Se omite.")
            continue

        class_label = class_id_to_label[class_id]
        color = CLASS_COLORS_ID.get(class_id, "#CCCCCC")

        path_nodes = get_path_nodes_for_class_pos(target_pos)
        if not path_nodes:
            print(f"(i) No hay camino para la clase: {class_label} (ID={class_id})")
            continue

        dot = graphviz.Digraph(
            comment=f"Caminos hacia {class_label}",
            graph_attr={
                "dpi": str(dpi),
                "rankdir": "TB",
                "splines": "true",
                "nodesep": "0.35",
                "ranksep": "0.45",
                "fontname": node_font,
            },
            node_attr={
                "shape": "box",
                "style": "filled,rounded",
                "fontname": node_font,
                "fontsize": "11",
                "penwidth": "1.5",
                "color": "black",
            },
            edge_attr={
                "fontname": edge_font,
                "fontsize": "10",
                "color": "black",
                "arrowsize": "0.7",
            },
        )

        def add_nodes_and_edges(u: int):
            if u not in path_nodes:
                return

            counts, probs = counts_probs_for_node(u)
            samples = int(tree.n_node_samples[u])
            gini = float(tree.impurity[u])

            # Mayoría en este nodo (posición → ID → etiqueta)
            maj_pos = int(pred_cls_idx_local[u])
            maj_id  = model_class_ids[maj_pos]
            majority_label = class_id_to_label[maj_id]

            if is_leaf[u]:
                label = (
                    f"samples = {samples}\n"
                    f"value = {fmt_counts(counts)}\n"
                    f"probs = {fmt_probs(probs)}\n"
                    f"class = {majority_label}"
                )
                dot.node(str(u), label=label, fillcolor=color, shape="ellipse")
            else:
                feat_idx = int(tree.feature[u])
                if 0 <= feat_idx < len(feature_names):
                    feat_name = feature_names[feat_idx]
                else:
                    feat_name = f"Feature_{feat_idx}"

                thr = float(tree.threshold[u])
                label = (
                    f"{feat_name} <= {thr:.3f}\n"
                    f"gini = {gini:.3f} | samples = {samples}\n"
                    f"value = {fmt_counts(counts)}\n"
                    f"probs = {fmt_probs(probs)}\n"
                    f"class = {majority_label}"
                )
                dot.node(str(u), label=label, fillcolor=color, shape="box")

                lc = int(children_left[u])
                rc = int(children_right[u])
                if lc in path_nodes:
                    dot.edge(str(u), str(lc), label="True")
                    add_nodes_and_edges(lc)
                if rc in path_nodes:
                    dot.edge(str(u), str(rc), label="False")
                    add_nodes_and_edges(rc)

        add_nodes_and_edges(0)

        out_name = f"{out_prefix}{_safe_name(class_label)}"
        try:
            dot.render(out_name, format="png", cleanup=True)
            print(f"✓ Guardado: {out_name}.png (Clase: {class_label}, ID={class_id})")
            display(IPImage(filename=f"{out_name}.png"))
        except Exception as e:
            print(f"✗ Error generando gráfico para {class_label} (ID={class_id}): {e}")


