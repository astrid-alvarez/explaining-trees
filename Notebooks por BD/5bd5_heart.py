def calcular_consistencia_final(shap_vals_list, feature_list, class_list, k=5, mapa=None):
    resultados = []

    if hasattr(feature_list, 'tolist'): feature_list = feature_list.tolist()

    for i, class_id in enumerate(class_list):
        # 1. TRADUCCIÓN: Obtener nombre real para buscar el archivo
        # Si el mapa es None o falla, usa el ID como string
        nombre_real = mapa.get(class_id, str(class_id)) if mapa else str(class_id)

        print(f"Analizando consistencia para: '{nombre_real}'...")

        # 2. RECONSTRUIR NOMBRE DEL ARCHIVO CSV (Igual que en Parte 12)
        # Nota: En Parte 12 usualmente se guarda en minúsculas (.lower())
        safe_name = str(nombre_real).lower()\
            .replace(' ', '_')\
            .replace('>', 'gt')\
            .replace('<', 'lt')\
            .replace('/', '_')

        filename_csv = f"reglas_especializadas_clase_{safe_name}.csv"

        # 3. OBTENER FEATURES DEL ÁRBOL
        top_k_feats_tree = set()

        if os.path.exists(filename_csv):
            try:
                df_rules = pd.read_csv(filename_csv)
                top_rules = df_rules.head(20) # Muestra representativa

                feat_counter = {}
                for cond_str in top_rules['conditions']:
                    if pd.isna(cond_str): continue
                    for feat in feature_list:
                        if feat in cond_str:
                            feat_counter[feat] = feat_counter.get(feat, 0) + 1

                sorted_feats_tree = sorted(feat_counter, key=feat_counter.get, reverse=True)[:k]
                top_k_feats_tree = set(sorted_feats_tree)
                print(f"  ✓ Archivo CSV encontrado. Top Features Árbol: {len(top_k_feats_tree)}")
            except Exception as e:
                print(f"  ⚠ Error leyendo {filename_csv}: {e}")
        else:
            print(f"  ⚠ Advertencia: No se encontró '{filename_csv}'")

        # 4. OBTENER FEATURES DE SHAP
        # shap_vals_list[i] corresponde al índice i
        mean_abs_shap = np.mean(np.abs(shap_vals_list[i]), axis=0)
        top_indices_shap = np.argsort(mean_abs_shap)[::-1][:k]
        top_k_feats_shap = set([feature_list[idx] for idx in top_indices_shap])

        # 5. CALCULAR JACCARD
        intersection = top_k_feats_shap.intersection(top_k_feats_tree)
        union = top_k_feats_shap.union(top_k_feats_tree)

        jaccard = len(intersection) / len(union) if len(union) > 0 else 0.0

        resultados.append({
            "Clase": nombre_real,  # Nombre bonito para el reporte
            "Jaccard_Index": round(jaccard, 4),
            "Coincidencias": len(intersection),
            "Features_Comunes": list(intersection)
        })

    return pd.DataFrame(resultados)

